SPACE_ADVANCE = 4


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    chars = sorted(G)
    width = sum(len(G[c][0]) + 1 for c in chars) + 1
    img = Image.new("RGBA", (width, HEIGHT), (0, 0, 0, 0))
    meta = {"height": HEIGHT, "ascent": ASCENT, "space": SPACE_ADVANCE, "glyphs": {}}
    x = 1
    for c in chars:
        rows = G[c]
        w = len(rows[0])
        assert all(len(r) == w for r in rows), c
        assert len(rows) in (7, 9), c
        for y, row in enumerate(rows):
            for i, ch in enumerate(row):
                if ch == "#":
                    img.putpixel((x + i, 1 + y), (255, 255, 255, 255))
        meta["glyphs"][str(ord(c))] = {"x": x, "w": w, "advance": w + 1}
        x += w + 1
    img.save(OUT / "pixel.png")
    (OUT / "pixel.json").write_text(json.dumps(meta, indent=1, sort_keys=True) + "\n")
    print("wrote", OUT / "pixel.png", len(chars), "glyphs")


if __name__ == "__main__":
    main()
